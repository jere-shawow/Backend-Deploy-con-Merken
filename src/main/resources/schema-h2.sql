-- Solo para H2 (spring.sql.init.platform=h2): perfil local "h2" y pruebas.
-- En MySQL no se ejecuta: Hibernate crea las tablas con todas sus columnas.
-- Migración idempotente: se ejecuta en cada arranque, ANTES de que Hibernate valide/actualice el esquema.
-- En una base nueva la tabla astronauts aún no existe y los ALTER no hacen nada (Hibernate la crea completa).
-- En una base creada con versiones anteriores, agrega lo que falte.

-- v2: nutrición y oxígeno
ALTER TABLE IF EXISTS astronauts ADD COLUMN IF NOT EXISTS nutrition INTEGER;
ALTER TABLE IF EXISTS astronauts ADD COLUMN IF NOT EXISTS oxygen_in_blood DOUBLE PRECISION;

-- v3: estado del vínculo Garmin en el astronauta
ALTER TABLE IF EXISTS astronauts ADD COLUMN IF NOT EXISTS garmin_linked BOOLEAN DEFAULT FALSE;
ALTER TABLE IF EXISTS astronauts ADD COLUMN IF NOT EXISTS garmin_last_sync TIMESTAMP(6) WITH TIME ZONE;

-- v3: variables globales de la aplicación
CREATE TABLE IF NOT EXISTS app_settings (
    id BIGINT NOT NULL PRIMARY KEY,
    refresh_interval_seconds INTEGER NOT NULL
);

-- v3: vínculos con Garmin Connect (Personal API)
CREATE TABLE IF NOT EXISTS garmin_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    astronaut_id BIGINT NOT NULL UNIQUE,
    api_key VARCHAR(2000) NOT NULL,
    linked_at TIMESTAMP(6) WITH TIME ZONE,
    last_sync_at TIMESTAMP(6) WITH TIME ZONE,
    last_error VARCHAR(500)
);
